// npm run docker
//
// Starts the whole project in Docker with one command: PostgreSQL, Redis,
// database migrations, the API and the web app, at http://localhost:8080.
//
// The first run creates a .env file with freshly generated secrets.
// Press Ctrl+C to stop. `npm run docker:stop` removes the containers and keeps
// the data; `npm run docker:reset` also erases the local database and secrets.

import { spawn, spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const envFile = path.join(root, ".env");

function fail(message) {
  console.error(`\n\x1b[31m✖ ${message}\x1b[0m\n`);
  process.exit(1);
}

if (spawnSync("docker", ["info"], { stdio: "ignore" }).status !== 0) {
  fail("Docker is not running. Start Docker Desktop, wait until it is ready, and run this again.");
}

// npm run docker:reset
// Removes the containers, the local database and the generated secrets, so the
// next `npm run docker` starts from nothing. It talks to Docker directly
// because `docker compose` refuses to run at all without a .env file.
if (process.argv.includes("--reset")) {
  const docker = (...args) => spawnSync("docker", args, { encoding: "utf8" });
  const containers = docker("ps", "-aq", "--filter", "label=com.docker.compose.project=linkforge").stdout.split("\n").filter(Boolean);
  if (containers.length > 0) docker("rm", "-f", ...containers);
  docker("volume", "rm", "linkforge_pgdata");
  docker("network", "rm", "linkforge_default");
  fs.rmSync(envFile, { force: true });
  console.log("Removed the LinkForge containers, the local database and .env. Run `npm run docker` to start fresh.");
  process.exit(0);
}

if (!fs.existsSync(envFile)) {
  // PostgreSQL stores its password inside the data volume the first time it
  // starts. A new .env means a new password, which an existing volume would
  // reject. Stop here with the two ways out instead of failing halfway.
  const volumeExists = spawnSync("docker", ["volume", "inspect", "linkforge_pgdata"], { stdio: "ignore" }).status === 0;
  if (volumeExists) {
    fail(
      "There is no .env file, but a LinkForge database from an earlier run still exists.\n" +
        "  Its password was in the old .env, so new secrets would not be able to open it.\n\n" +
        "  Either put the old .env file back,\n" +
        "  or erase the old local database and start fresh:  npm run docker:reset"
    );
  }

  const secret = (bytes) => crypto.randomBytes(bytes).toString("hex");
  fs.writeFileSync(
    envFile,
    [
      "# Generated by `npm run docker`. Keep this file private; it is git-ignored.",
      `POSTGRES_PASSWORD=${secret(16)}`,
      `JWT_ACCESS_SECRET=${secret(32)}`,
      `IP_HASH_SALT=${secret(32)}`,
      "",
    ].join("\n"),
    { mode: 0o600 }
  );
  console.log("Created .env with new secrets.");
}

console.log("\nStarting LinkForge. When the containers are up, open http://localhost:8080\n");

const compose = spawn("docker", ["compose", "up", "--build"], { cwd: root, stdio: "inherit" });
compose.on("exit", (code) => process.exit(code ?? 0));

// Ctrl+C reaches docker compose directly, which stops the containers gracefully.
process.on("SIGINT", () => {});
process.on("SIGTERM", () => compose.kill("SIGTERM"));
